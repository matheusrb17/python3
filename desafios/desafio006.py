#valores de um numero

n1 = float(input('Digite um valor: '))
dobro = n1 * 2
triplo = n1 * 3
raiz = n1 ** 0.5
print('O número digitado é: {}'.format(n1))
print('O dobro de {} é: {}'.format(n1, dobro))
print('O triplo de {} é: {}'.format(n1, triplo))
print('A raiz quadrada de {} é: {}'.format(n1, raiz))
